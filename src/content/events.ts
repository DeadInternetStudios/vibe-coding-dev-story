/* ---------------------------------------------------------------- predicates */

type When = (c: EventCtx) => boolean;
const always: When = () => true;
const has = (id: string): When => (c) => c.company.hasArchetype(id);
const lacks = (id: string): When => (c) => !c.company.hasArchetype(id);
const all = (...ps: When[]): When => (c) => ps.every((p) => p(c));
const some = (...ps: When[]): When => (c) => ps.some((p) => p(c));
const year = (min: number, max = 3): When => (c) => c.company.year >= min && c.company.year <= max;
const months = (...m: number[]): When => (c) => m.includes(c.company.month);
const cashUnder = (n: number): When => (c) => c.company.cash < n;
const karmaOver = (n: number): When => (c) => c.company.karma >= n;
const staffOver = (n: number): When => (c) => c.company.staffCount >= n;
const spaghettiOver = (n: number): When => (c) => c.company.spaghetti > n;
const shippedOver = (n: number): When => (c) => c.company.appsShipped >= n;
const toolIs = (...ids: string[]): When => (c) => c.project !== null && ids.includes(c.project.tool);
const statUnder = (k: StatKey, n: number): When => (c) => c.project !== null && c.project.stats[k] < n;

/* ------------------------------------------------------------------- effects */

