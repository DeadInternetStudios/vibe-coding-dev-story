/** Width in pixels of `text` with `gap` pixels between letters. */
export function glyphWidth(text: string, gap = 1): number {
  return text.length * (3 + gap) - gap;
}

/** Writes `text` with its top left at (x, y). Returns the width used. */
export function glyphs(p: Px, text: string, x: number, y: number, c: Ink | InkName, gap = 1): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch];
    if (g) for (let gy = 0; gy < 5; gy++) for (let gx = 0; gx < 3; gx++) if (g[gy]![gx] === '1') p.set(cx + gx, y + gy, c);
    cx += 3 + gap;
  }
  return cx - x - gap;
}

/** The raw rows of one letter, for sprites that want to recolor or reshape it. */
export function glyphRows(ch: string): readonly string[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS[' ']!;
}
