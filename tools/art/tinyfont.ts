/** Width in pixels of `text` at `scale`, one pixel of space between letters. */
export function textWidth(text: string, scale = 1): number {
  return text.length * 4 * scale - scale;
}

/** Calls `plot(x, y)` for every lit pixel. Unknown characters are skipped. */
export function drawText(plot: (x: number, y: number) => void, text: string, x: number, y: number, scale = 1): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch];
    if (g) {
      for (let gy = 0; gy < 5; gy++)
        for (let gx = 0; gx < 3; gx++)
          if (g[gy]![gx] === '1') for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) plot(cx + gx * scale + sx, y + gy * scale + sy);
    }
    cx += 4 * scale;
  }
}
